# Synthetic Atuin/Nushell checks. Never run real history, sync, login or shells.
$ErrorActionPreference = 'Stop'
$Repository = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
. (Join-Path $Repository 'scripts/windows/dotfiles.ps1')

function Assert-True {
    param([bool] $Condition, [string] $Message)
    if (-not $Condition) { throw $Message }
}

$Fixture = Join-Path ([IO.Path]::GetTempPath()) ('dotfiles-atuin-test-' + [guid]::NewGuid().ToString('N'))
$SavedHome = $HOME
$SavedConfig = $env:ATUIN_CONFIG_DIR
$script:AtuinAvailable = $true
$script:AtuinExit = 0
$script:NuExit = 0
$script:AtuinCalls = [Collections.Generic.List[object]]::new()
$script:NuCalls = [Collections.Generic.List[object]]::new()
$script:KeyHandlers = @{}

function Get-Command {
    param([string] $Name, [object] $ErrorAction)
    if ($Name -eq 'sk' -or ($Name -eq 'atuin' -and $script:AtuinAvailable)) {
        [pscustomobject]@{ Name = $Name }
    }
}
function Get-Module {
    param([string] $Name, [switch] $ListAvailable)
    if ($Name -eq 'PSReadLine') { [pscustomobject]@{ Name = $Name } }
}
function Import-Module { param([string] $Name) }
function Set-PSReadLineKeyHandler {
    param([string] $Chord, [string] $BriefDescription, [string] $LongDescription, [scriptblock] $ScriptBlock)
    $script:KeyHandlers[$Chord] = @{} + $PSBoundParameters
}
function atuin {
    $script:AtuinCalls.Add(@($args))
    $global:LASTEXITCODE = $script:AtuinExit
    if ($script:AtuinExit -ne 0) { return }
    if (($args -join '|') -eq 'init|powershell|--disable-up-arrow|--disable-ai') {
        return 'Set-PSReadLineKeyHandler -Chord Ctrl+r -BriefDescription AtuinSearch -ScriptBlock { }'
    }
    if (($args -join '|') -eq 'init|nu|--disable-up-arrow|--disable-ai') {
        return '# synthetic Nu integration; never evaluated'
    }
    throw 'Unexpected Atuin invocation: only init is allowed'
}
function nu {
    $script:NuCalls.Add(@($args))
    Assert-True ($args.Count -eq 3 -and $args[0] -eq '--no-config-file' -and $args[1] -eq '--commands') 'Bootstrap must not start interactive Nu or read its user configuration'
    Assert-True ($args[2] -eq '$nu.data-dir | path join "vendor" "autoload"') 'Ask Nu for its own autoload location'
    $global:LASTEXITCODE = $script:NuExit
    if ($script:NuExit -eq 0) { return $script:Autoload }
}

try {
    Set-Variable -Name HOME -Value (Join-Path $Fixture 'home with spaces') -Force
    New-Item -ItemType Directory -Path $HOME -Force | Out-Null
    $script:Autoload = Join-Path $Fixture 'AppData - fixture [test]/nushell/vendor/autoload'
    $env:ATUIN_CONFIG_DIR = $null
    $Skim = Join-Path $Repository 'powershell/.config/powershell/20-skim.ps1'
    $Atuin = Join-Path $Repository 'powershell/.config/powershell/25-atuin.ps1'
    . $Skim
    . $Atuin
    Assert-True ($script:KeyHandlers['Ctrl+r'].BriefDescription -eq 'AtuinSearch') 'Atuin must take Ctrl+R after skim'
    Assert-True ($script:KeyHandlers['Ctrl+t'].BriefDescription -eq 'SkimFiles') 'Skim must retain Ctrl+T'
    Assert-True (-not $script:KeyHandlers.ContainsKey('UpArrow')) 'Do not take over Up Arrow'
    Assert-True ($env:ATUIN_CONFIG_DIR -eq (Join-Path $HOME '.config/atuin')) 'Use the Stow-managed Atuin configuration'

    $env:ATUIN_CONFIG_DIR = Join-Path $Fixture 'explicit user override'
    . $Atuin
    Assert-True ($env:ATUIN_CONFIG_DIR -eq (Join-Path $Fixture 'explicit user override')) 'Respect an explicit Atuin configuration directory'

    $script:AtuinAvailable = $false
    $CallCount = $script:AtuinCalls.Count
    . $Skim
    . $Atuin
    Assert-True ($script:AtuinCalls.Count -eq $CallCount -and $script:KeyHandlers['Ctrl+r'].BriefDescription -eq 'SkimHistory') 'Missing Atuin must retain the skim fallback'
    $script:AtuinAvailable = $true
    $script:AtuinExit = 1
    . $Atuin 3>$null
    Assert-True ($script:KeyHandlers['Ctrl+r'].BriefDescription -eq 'SkimHistory') 'Failed Atuin init must retain the existing binding'
    $script:AtuinExit = 0

    $Config = Join-Path $Fixture 'AppData - fixture [test]/nushell/config.nu'
    New-Item -ItemType Directory -Path (Split-Path -Parent $Config) -Force | Out-Null
    Set-Content -LiteralPath $Config -Value '# synthetic existing user configuration'
    Install-AtuinNushellIntegration
    $Generated = Join-Path $script:Autoload 'dotfiles-atuin.nu'
    $Original = Get-Content -LiteralPath $Generated -Raw
    Assert-True ($Original -match 'Generated by dotfiles bootstrap' -and $Original -match 'synthetic Nu integration') 'Write the generated init script only to its own autoload file'
    Assert-True ($Original -match 'ATUIN_CONFIG_DIR') 'Nu launched outside PowerShell must also find the managed configuration'
    Set-Content -LiteralPath (Join-Path $script:Autoload 'user.nu') -Value '# synthetic unrelated autoload file'
    Install-AtuinNushellIntegration
    Assert-True ((Get-Content -LiteralPath $Generated -Raw) -eq $Original) 'Repeated setup should refresh its own integration consistently'
    Assert-True ((Get-Content -LiteralPath $Config -Raw).Trim() -eq '# synthetic existing user configuration') 'Do not replace Nu config.nu'
    Assert-True ((Get-Content -LiteralPath (Join-Path $script:Autoload 'user.nu') -Raw).Trim() -eq '# synthetic unrelated autoload file') 'Do not replace unrelated autoload files'

    $script:NuExit = 1
    $Rejected = $false
    try { Install-AtuinNushellIntegration } catch { $Rejected = $_.Exception.Message -like 'Could not determine*' }
    Assert-True $Rejected 'Nu path query failures must stop setup'
    $script:NuExit = 0
    $script:AtuinExit = 1
    $Rejected = $false
    try { Install-AtuinNushellIntegration } catch { $Rejected = $_.Exception.Message -like 'Could not generate*' }
    Assert-True ($Rejected -and (Get-Content -LiteralPath $Generated -Raw) -eq $Original) 'Failed generation must preserve the previous integration'
    $script:AtuinExit = 0

    Set-Content -LiteralPath $Generated -Value '# synthetic user-owned file'
    $Rejected = $false
    try { Install-AtuinNushellIntegration } catch { $Rejected = $_.Exception.Message -like 'Existing Nushell integration*' }
    Assert-True ($Rejected -and (Get-Content -LiteralPath $Generated -Raw).Trim() -eq '# synthetic user-owned file') 'An unmarked existing file must not be overwritten'

    Remove-Item -LiteralPath $Generated
    $LinkTarget = Join-Path $Fixture 'synthetic target.nu'
    Set-Content -LiteralPath $LinkTarget -Value '# synthetic user-owned target'
    New-Item -ItemType SymbolicLink -Path $Generated -Target $LinkTarget | Out-Null
    $Rejected = $false
    try { Install-AtuinNushellIntegration } catch { $Rejected = $_.Exception.Message -like 'Existing Nushell integration*' }
    Assert-True ($Rejected -and (Get-Content -LiteralPath $LinkTarget -Raw).Trim() -eq '# synthetic user-owned target') 'An existing integration symlink must not be followed or overwritten'

    $Bootstrap = Get-Content -LiteralPath (Join-Path $Repository 'bootstrap.ps1') -Raw
    Assert-True ($Bootstrap -match 'Install-AtuinNushellIntegration') 'Bootstrap must prepare the optional shell integration'
    Write-Output 'PASS: Atuin Ctrl+R/skim Ctrl+T, fallback, explicit config, optional Nu query, generated init refresh, user-file protection and failure handling'
} finally {
    Set-Variable -Name HOME -Value $SavedHome -Force
    $env:ATUIN_CONFIG_DIR = $SavedConfig
    if (Test-Path -LiteralPath $Fixture) { Remove-Item -LiteralPath $Fixture -Recurse -Force }
}
